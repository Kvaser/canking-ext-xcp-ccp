//! Traceability: where a generated artefact came from.
//!
//! A `.dbc` or `.t` file that turns up on its own is hard to place. Which A2L, which protocol, which signals, what DAQ/event setup.
//! Most of that is not recoverable from the file itself.
//!
//! [`traceability_lines`] renders those missing facts as plain text lines that the generated artefacts can embed as comments.

use crate::a2l::{A2lProject, CanIdSource};
use crate::daq::DaqList;
use crate::Protocol;
use std::fmt::Write;

/// Text helping with traceability, describing the source A2L, protocol, bus parameters, CAN identifiers, and the DAQ/event signal layout.
///
/// `source_name` is the source A2L file name.
///
/// `project` is the parsed A2L project.
///
/// `daq_lists` is the generated DAQ list layout.
///
/// `protocol` is the protocol used to generate the DAQ lists. (XCP, CCP, etc.)
pub fn traceability_lines(
    source_name: &str,
    project: &A2lProject,
    daq_lists: &[DaqList],
    protocol: Protocol,
) -> Vec<String> {
    let mut lines = Vec::new();

    let source = source_name.trim();
    let source = if source.is_empty() { "unknown" } else { source };
    lines.push(format!("Source A2L: {source}"));
    lines.push(format!("Protocol: {}", protocol.name()));

    // Bus parameters and CAN identifiers, per protocol.
    match protocol {
        Protocol::Xcp => {
            if let Some(info) = project.xcp_data.as_ref().and_then(|x| x.xcp_info.as_ref()) {
                if let Some(baud) = info.baudrate {
                    let mut bus = format!("Bus: {baud} bit/s");
                    if let Some(fd) = info.can_fd.as_ref() {
                        match fd.data_baudrate {
                            Some(data) => {
                                let _ = write!(bus, " (CAN FD, data {data} bit/s)");
                            }
                            None => bus.push_str(" (CAN FD)"),
                        }
                    }
                    lines.push(bus);
                }
                let mut ids = String::from("CAN IDs:");
                if let Some(m) = info.can_id_master {
                    let _ = write!(ids, " master 0x{m:X}");
                }
                if let Some(s) = info.can_id_slave {
                    let _ = write!(ids, " slave 0x{s:X}");
                }
                if ids != "CAN IDs:" {
                    lines.push(ids);
                }
            }
        }
        Protocol::Ccp => {
            if let Some(ccp) = project.ccp_data.as_ref() {
                if let Some(baud) = ccp.info.baudrate {
                    lines.push(format!("Bus: {baud} bit/s"));
                }
                lines.push(format!(
                    "CAN IDs: CRO 0x{:X}, DTO 0x{:X}",
                    ccp.info.cro_id, ccp.info.dto_id
                ));
            }
        }
    }

    // DAQ layout: total signals plus the signals assigned to each event.
    let mut total = 0usize;
    let mut event_lines = Vec::new();
    for daq in daq_lists {
        let mut names: Vec<&str> = Vec::new();
        for odt in &daq.odts {
            for entry in &odt.entries {
                for name in &entry.names {
                    if !names.contains(&name.as_str()) {
                        names.push(name.as_str());
                    }
                }
            }
        }
        total += names.len();
        let event = daq.event.as_deref().unwrap_or("(unassigned)");
        let last_pid = daq
            .first_pid
            .saturating_add(daq.odts.len().saturating_sub(1) as u16);
        let can_id_note = match daq.can_id {
            CanIdSource::Default => String::new(),
            CanIdSource::Fixed { id } => format!(", CAN 0x{id:X} (fixed)"),
            CanIdSource::Dynamic { assigned: Some(id) } => format!(", CAN 0x{id:X} (dynamic)"),
            CanIdSource::Dynamic { assigned: None } => {
                ", CAN id dynamic (unassigned, uses the default)".to_string()
            }
        };
        event_lines.push(format!(
            "  {event}: {}  (DAQ list {}, PID {}..{}{can_id_note})",
            names.join(", "),
            daq.id,
            daq.first_pid,
            last_pid
        ));
    }
    lines.push(format!(
        "DAQ: {} list(s), {} signal(s)",
        daq_lists.len(),
        total
    ));
    lines.extend(event_lines);

    lines.push(concat!("Generated by a2l-daq v", env!("CARGO_PKG_VERSION")).to_string());

    lines
}

// ------------------------------- Unit tests ------------------------------------------

#[cfg(test)]
mod tests {
    use super::*;
    use crate::a2l::{DaqInfo, EventInfo, XcpData, XcpInfo};
    use crate::daq::{Odt, OdtEntry};
    use crate::{CcpData, CcpInfo};

    fn odt(names: &[&str]) -> Odt {
        Odt {
            entries: names
                .iter()
                .map(|n| OdtEntry {
                    names: vec![(*n).into()],
                    ecu_address: 0x10,
                    size: 2,
                })
                .collect(),
        }
    }

    #[test]
    fn xcp_provenance_reports_source_protocol_bus_ids_and_events() {
        let project = A2lProject {
            xcp_data: Some(XcpData {
                daq_info: DaqInfo::default(),
                event_info: EventInfo::default(),
                xcp_info: Some(XcpInfo {
                    can_id_master: Some(0x455),
                    can_id_slave: Some(0x456),
                    baudrate: Some(500_000),
                    ..Default::default()
                }),
                protocol_layer: None,
            }),
            ..Default::default()
        };
        let daq = vec![DaqList {
            id: 0,
            first_pid: 0,
            event: Some("Task10ms".into()),
            odts: vec![odt(&["Rpm", "Speed"])],
            can_id: CanIdSource::Default,
        }];

        let lines = traceability_lines("demo.a2l", &project, &daq, Protocol::Xcp);
        let text = lines.join("\n");
        assert!(text.contains("Source A2L: demo.a2l"), "{text}");
        assert!(text.contains("Protocol: XCP"), "{text}");
        assert!(text.contains("Bus: 500000 bit/s"), "{text}");
        assert!(text.contains("master 0x455"), "{text}");
        assert!(text.contains("slave 0x456"), "{text}");
        assert!(text.contains("DAQ: 1 list(s), 2 signal(s)"), "{text}");
        assert!(text.contains("Task10ms: Rpm, Speed"), "{text}");
        assert!(text.contains("Generated by a2l-daq v"), "{text}");
    }

    #[test]
    fn ccp_traceability_reports_cro_dto_ids() {
        let project = A2lProject {
            ccp_data: Some(CcpData {
                info: CcpInfo {
                    cro_id: 0x455,
                    dto_id: 0x456,
                    baudrate: Some(250_000),
                    ..Default::default()
                },
                ..Default::default()
            }),
            ..Default::default()
        };
        let daq = vec![DaqList {
            id: 0,
            first_pid: 0,
            event: None,
            odts: vec![odt(&["Temp"])],
            can_id: CanIdSource::Default,
        }];

        let text = traceability_lines("", &project, &daq, Protocol::Ccp).join("\n");
        assert!(text.contains("Source A2L: unknown"), "{text}");
        assert!(text.contains("Protocol: CCP"), "{text}");
        assert!(text.contains("Bus: 250000 bit/s"), "{text}");
        assert!(text.contains("CRO 0x455, DTO 0x456"), "{text}");
        assert!(text.contains("(unassigned): Temp"), "{text}");
    }
}
